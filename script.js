const toggler = document.querySelector('.navbar-toggler');
const collapse = document.getElementById('navbarSupportedContent');

toggler.addEventListener('click', () => {
  const isCollapsed = collapse.classList.contains('show');

  toggler.classList.toggle('open');

  // Apply blur and scroll lock when opening
  if (!isCollapsed) {
    document.body.classList.add('no-scroll');
    document.getElementById('main-content').classList.add('blur-background');
  } else {
    document.body.classList.remove('no-scroll');
    document.getElementById('main-content').classList.remove('blur-background');
  }
});

// When menu is closed by Bootstrap event
collapse.addEventListener('hidden.bs.collapse', () => {
  toggler.classList.remove('open');
  document.body.classList.remove('no-scroll');
  document.getElementById('main-content').classList.remove('blur-background');
});

// When menu is shown by Bootstrap event (optional for safety)
collapse.addEventListener('shown.bs.collapse', () => {
  document.body.classList.add('no-scroll');
  document.getElementById('main-content').classList.add('blur-background');
});





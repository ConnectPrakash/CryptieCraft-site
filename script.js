document.querySelectorAll(".Craitrix-nav-items .nav-link").forEach(link => {
  link.addEventListener("click", function (e) {
    e.preventDefault();

    const dropdown = this.nextElementSibling;

    // Close other dropdowns
    document.querySelectorAll(".Craitrix-box").forEach(box => {
      if (box !== dropdown) {
        box.classList.remove("show");
        const closeBtn = box.querySelector(".close-btn");
        if (closeBtn) closeBtn.remove();
      }
    });

    // Toggle current dropdown
    const isOpen = dropdown.classList.contains("show");

    // Remove blur/scroll first
    document.body.classList.remove("no-scroll");
    document.getElementById("main-content").classList.remove("blur-background");

    // Toggle dropdown
    dropdown.classList.toggle("show");

    // If now opened, re-add blur and scroll lock
    if (dropdown.classList.contains("show")) {
      document.body.classList.add("no-scroll");
      document.getElementById("main-content").classList.add("blur-background");
    }


    // Add close button if dropdown is shown
    if (isOpen && !dropdown.querySelector(".close-btn")) {
      const closeBtn = document.createElement("div");
      closeBtn.className = "close-btn";
      closeBtn.innerHTML = `<i class="fa-solid fa-xmark"></i>`;
      dropdown.prepend(closeBtn);

      closeBtn.addEventListener("click", () => {
        dropdown.classList.remove("show");
        closeBtn.remove();
        document.body.classList.remove("no-scroll");
        document.getElementById("main-content").classList.remove("blur-background");
      });
    }
  });
});


// Handle dropdown click
function listEventHandler(e) {
  const link = e.target.closest('.nav-link');
  if (!link) return;

  // remove All previous nav-active 
  document.querySelectorAll(".Craitrix-nav-items .nav-link").forEach(link => {
    link.classList.remove("nav-active")
  });

  link.classList.add("nav-active");
  const item_name = link.getAttribute('name');
  const parentLi = link.closest('li');
  const boxInside = parentLi.querySelector('.Craitrix-box');
  const boxBelow = document.querySelector('.Craitrix-downbox');
  const isMobile = window.innerWidth < 992;

  const alreadyOpen = isMobile
    ? boxInside.style.display === 'block'
    : boxBelow.style.display === 'block' && boxBelow.dataset.active === item_name;

  // Hide all previous boxes and reset arrows
  document.querySelectorAll('.Craitrix-box').forEach(box => {
    box.style.display = 'none';
    box.innerHTML = '';
  });
  document.querySelectorAll('.arrow-icon').forEach(icon => icon.classList.remove('rotate-arrow'));

  boxBelow.innerHTML = '';
  boxBelow.style.display = 'none';
  boxBelow.removeAttribute('data-active');

  if (alreadyOpen) return;

  const selected = data.find(ele => ele.name === item_name);
  const targetBox = isMobile ? boxInside : boxBelow;

  if (!selected || !selected.tabs) {
    targetBox.innerHTML = `<div class="text-muted">No data available for "${item_name}"</div>`;
  } else {
    // Tab headers
    const wrapper = document.createElement("div");
    wrapper.className = "dropdown-wrapper";

    // Add close (exit) button
    const closeBtn = document.createElement("button");
    closeBtn.className = "close-btn";
    closeBtn.innerHTML = `<i class="fa-solid fa-xmark"></i>`;
    closeBtn.style.cssText = `
      position:absolute;
      right:20px;
      background:#f8f9fb;
      color:black;
      border: none;
      font-size: 20px;
      cursor: pointer;
    `;

    closeBtn.addEventListener('click', () => {
      targetBox.style.display = 'none';
      targetBox.innerHTML = '';
      targetBox.removeAttribute('data-active');
      link.classList.remove("nav-active");
      document.body.classList.remove("no-scroll");
      document.getElementById("main-content").classList.remove("blur-background");
      document.querySelectorAll('.arrow-icon').forEach(icon => icon.classList.remove('rotate-arrow'));
    });

    // Tab headers
    const tabHeader = document.createElement("div");
    const tabHeaderContainer = document.createElement("div");
    tabHeader.className = "tab-header";

    tabHeader.appendChild(closeBtn);
    tabHeaderContainer.className = "tab-header-button";

    selected.tabs.forEach((tab, i) => {
      const btn = document.createElement("button");
      btn.className = "tab-btn" + (i === 0 ? " navactive" : "");
      btn.textContent = tab.tabTitle;
      btn.setAttribute("data-tab", i);
      tabHeaderContainer.appendChild(btn);
    });

    tabHeader.appendChild(tabHeaderContainer);
    wrapper.appendChild(tabHeader);

    // Tab contents
    const contentContainer = document.createElement("div");
    contentContainer.className = "tab-content";

    selected.tabs.forEach((tab, i) => {
      const tabPane = document.createElement("div");
      tabPane.className = "tab-pane" + (i === 0 ? " navactive" : "");

      tab.items.forEach(entry => {
        const div = document.createElement("div");
        div.className = "card-entry";
        div.style.backgroundColor = entry.color || "#fff";
        div.innerHTML = `
          <div class="item-content" style="display: flex; gap: 10px; align-items: center; padding: 10px;">
            <img src="${entry.icons}" alt="${entry.name}"  />
            <div>
              <h6 style="margin: 0 0 5px 0;">${entry.name}</h6>
              <p style="margin: 0; font-size: 12px; color: black;">${entry.desc}</p>
            </div>
          </div>
        `;
        tabPane.appendChild(div);
      });

      contentContainer.appendChild(tabPane);
    });

    wrapper.appendChild(contentContainer);
    targetBox.appendChild(wrapper);

    // Tab switching
    tabHeader.querySelectorAll('.tab-btn').forEach(btn => {
      btn.addEventListener('click', () => {
        const tabIndex = btn.getAttribute('data-tab');

        tabHeader.querySelectorAll('.tab-btn').forEach(b => b.classList.remove('navactive'));
        contentContainer.querySelectorAll('.tab-pane').forEach(pane => pane.classList.remove('navactive'));

        btn.classList.add('navactive');
        contentContainer.querySelectorAll('.tab-pane')[tabIndex].classList.add('navactive');
      });
    });
  }

  if (!isMobile) {
    boxBelow.setAttribute('data-active', item_name);
  }

  targetBox.style.display = 'block';

  // Rotate current arrow icon
  const arrow = link.querySelector('.arrow-icon');
  if (arrow) {
    arrow.classList.add('rotate-arrow');
  }
}

document.addEventListener('click', function (e) {
  const isToggler = e.target.closest('.navbar-toggler');
  const isDropdownNavItem = e.target.closest('.nav-item.dropdown');
  const isBox = e.target.closest('.Craitrix-box');
  const isDownbox = e.target.closest('.Craitrix-downbox');

  if (!isToggler && !isDropdownNavItem && !isBox && !isDownbox) {

    // Close all dropdowns
    document.querySelectorAll('.Craitrix-box').forEach(box => {
      box.classList.remove('show');
      box.style.display = 'none';
      box.innerHTML = '';
    });

    const downbox = document.querySelector('.Craitrix-downbox');
    if (downbox) {
      downbox.innerHTML = '';
      downbox.style.display = 'none';
      downbox.removeAttribute('data-active');
    }

    // Remove active nav and arrows
    document.querySelectorAll('.Craitrix-nav-items .nav-link').forEach(link => {
      link.classList.remove('nav-active');
    });

    document.querySelectorAll('.arrow-icon').forEach(icon => {
      icon.classList.remove('rotate-arrow');
    });

    // ✅ Remove blur and scroll lock
    document.body.classList.remove("no-scroll");
    document.getElementById("main-content").classList.remove("blur-background");
  }
});



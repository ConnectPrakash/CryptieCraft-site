let currentTab = "core";

function showTab(tab) {
  currentTab = tab;

  // Update button active state
  document.querySelectorAll(".feature-btn").forEach(btn => {
    btn.classList.remove("active");
    if (btn.textContent.toLowerCase().includes(tab)) {
      btn.classList.add("active");
    }
  });

  // Generate feature list
  const listContainer = document.querySelector(".feature-list");
  listContainer.innerHTML = "";

  featureData[tab].forEach((feature, index) => {
    const li = document.createElement("li");
    li.innerHTML = `${feature.title} <i class="fa-solid fa-arrow-right"></i>`;
    li.onclick = () => changeFeature(index);
    if (index === 0) li.classList.add("active1");
    listContainer.appendChild(li);
  });

  changeFeature(0); // Show first feature by default
}

function changeFeature(index) {
  console.log(currentTab);
  const selectedFeature = featureData[currentTab][index];
  console.log(selectedFeature);
  document.querySelectorAll(".feature-list li").forEach((li, i) => {
    li.classList.toggle("active1", i === index);
  });

  document.getElementById("feature-title").textContent = selectedFeature.title;
  document.getElementById("feature-desc").textContent = selectedFeature.desc;
  document.getElementById("feature-img").src = selectedFeature.img;
}


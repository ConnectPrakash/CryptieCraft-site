// Fix 2: Attach toggle logic after FAQs are rendered
document.querySelectorAll(".faq-question-content").forEach((question) => {
  question.addEventListener("click", () => {
    const index = question.getAttribute("data-index");
    const target = document.getElementById(`faq-answer-${index}`);
    const isCurrentlyVisible = target.style.display === "flex";

    // Hide all
    document.querySelectorAll(".faq-answer-content").forEach((ans) => {
      ans.style.display = "none";
    });

    // Toggle current (only show if it wasn't already visible)
    if (!isCurrentlyVisible) {
      target.style.display = "flex";
    }
  });
});





